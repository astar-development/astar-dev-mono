using Microsoft.CodeAnalysis;

namespace AStarDev.SourceGenerators.StrongIdCodeGeneration;

internal static class StrongIdCodeGenerator
{
    private const string AutoGeneratedComment = "// <auto-generated/>";
    private const string Usings = "using System;\nusing System.Collections.Generic;";

    public static string Generate(StrongIdModel model)
    {
        string ns = model.Namespace is null ? string.Empty : $"namespace {model.Namespace};";
        string accessibility = model.Accessibility == Accessibility.Internal ? "internal" : "public";
        string underlying = GetRequiredUnderlyingIdType(model);
        string documentation = $"/// <summary>A strongly-typed identifier wrapping a <see cref=\"{underlying}\"/> value.</summary>\n/// <param name=\"Value\">The underlying identifier value.</param>";

        string code = $"{AutoGeneratedComment}\n\n{Usings}\n\n{(string.IsNullOrEmpty(ns) ? string.Empty : ns)}\n\n{documentation}\n{accessibility} readonly partial record struct {model.ModelName}({underlying} Value)\n";
        code += $"{{\n    /// <inheritdoc />\n    public static implicit operator {model.ModelName}({underlying} value) => new {model.ModelName}(value);\n\n    /// <inheritdoc />\n    public static implicit operator {underlying}({model.ModelName} id) => id.Value;\n}}";

        return code;
    }

    private static string GetRequiredUnderlyingIdType(StrongIdModel model)
    {
        string underlying = model.UnderlyingTypeDisplay;
        if (string.IsNullOrEmpty(underlying))
            return "System.Guid";

        if (underlying.IndexOf('.') < 0)
        {
            switch (underlying)
            {
                case "Guid":
                    underlying = "System.Guid";
                    break;
                case "string":
                    underlying = "System.String";
                    break;
                case "int":
                    underlying = "System.Int32";
                    break;
                case "long":
                    underlying = "System.Int64";
                    break;
            }
        }

        return underlying;
    }
}
